"""`mra forms`: a Google Apps Script that builds one Google Form per stakeholder group from the item bank.

The forms are generated from the same form spec the analysis uses to read the CSV exports back (titles, grid
rows, options), so the two cannot drift apart. Run the script once at script.google.com (paste, then run
`createForms`); it logs the edit and response links of each form.

Settings follow the participant pack: no e-mail collection, no sign-in, every question optional, a progress
bar, pages in the agreed order. Apps Script cannot shuffle answer options; the script lists the scenario items
to set to "shuffle option order" by hand.
"""

from __future__ import annotations

import json

from .axes import derive_current_state
from .engagement import load_facts
from .instrument import load_instrument

PAGES = {1: "About you", 2: "Your experience", 3: "Decisions and alignment", 4: "Your preference",
         5: "How the options might affect you", 6: "In your own words"}
PAGE_NOTES = {5: "This page is optional. Your answers are only reported for groups of five or more people and "
                 "never used to weight anyone's answers."}
SHUFFLE = ["MD01", "MD02", "MD03", "MD06", "MO04"]
GROUP_NAMES = {"ENG": "Engineering", "PRD": "Product", "BUS": "Business", "TEC": "Technology leadership",
               "EXE": "Business leadership", "OPS": "Operations", "SEC": "Security, risk and compliance", "FIN": "Finance"}

COVER = ("{organisation} is reviewing how {system} should develop over the coming years. No option has been chosen. "
         "Keeping the current setup as it is, improving it, restructuring it, or changing where it runs are all on the "
         "table, and each will be judged against the same evidence.\n\n"
         "This survey asks about your day-to-day experience. There are no right or wrong answers. We do not collect "
         "names or e-mail addresses, and results are only reported for groups of five or more. Every question is "
         "optional; skip anything you prefer not to answer. \"Don't know\" is a useful answer — please use it rather "
         "than guess.")

SCRIPT = r"""/**
 * Generated by `mra forms` — do not edit by hand; regenerate from the item bank instead.
 * Paste into a new project at https://script.google.com and run createForms().
 * After creation, set "Shuffle option order" by hand for: __SHUFFLE__
 */
const SPEC = __SPEC__;

function createForms() {
  SPEC.forms.forEach(function (spec) {
    const form = FormApp.create(spec.title);
    form.setDescription(spec.description);
    form.setCollectEmail(false);
    form.setLimitOneResponsePerUser(false);
    form.setAllowResponseEdits(false);
    form.setProgressBar(true);
    form.setShowLinkToRespondAgain(false);
    let page = null;
    spec.questions.forEach(function (q) {
      if (q.page !== page) {
        if (page !== null) {
          const brk = form.addPageBreakItem().setTitle(SPEC.pages[q.page]);
          if (SPEC.notes[q.page]) brk.setHelpText(SPEC.notes[q.page]);
        }
        page = q.page;
      }
      let item;
      if (q.kind === "grid") {
        item = form.addGridItem().setRows(q.rows).setColumns(q.options);
      } else if (q.kind === "paragraph") {
        item = form.addParagraphTextItem();
      } else if (q.kind === "short") {
        item = form.addTextItem();
      } else {
        item = form.addMultipleChoiceItem().setChoiceValues(q.options);
      }
      item.setTitle(q.title).setRequired(false);
    });
    Logger.log(spec.group + ": edit " + form.getEditUrl() + " | respond " + form.getPublishedUrl());
  });
}
"""


def form_specs(engagement_path) -> dict:
    """The data the Apps Script needs: one form per group, questions in page order, titles as exported."""
    from pathlib import Path

    import yaml

    path = Path(engagement_path).resolve()
    cfg = yaml.safe_load(path.read_text())
    root = path.parent
    ins = load_instrument(root / cfg.get("instrument", "instrument"))
    facts = load_facts(root / cfg["facts"]) if cfg.get("facts") else {}
    current = {"architecture": derive_current_state(ins, facts), "hosting": cfg.get("current_hosting", "own_infrastructure")}
    system = cfg.get("system", "the system")
    report = cfg.get("report", {}) or {}
    groups = list((cfg.get("responses") or {}).keys()) or list(GROUP_NAMES)
    forms = []
    for role in groups:
        questions, grids = [], {}
        for q in ins.form_spec(role, system, current, cfg.get("consistency_example", "")):
            if q["row"] is not None:
                if q["item_id"] not in grids:
                    grids[q["item_id"]] = {"item_id": q["item_id"], "page": q["page"], "kind": "grid", "title": q["text"],
                                           "rows": [], "options": q["options"]}
                    questions.append(grids[q["item_id"]])
                grids[q["item_id"]]["rows"].append(q["row"])
                continue
            kind = "short" if q["item_id"] == "CX03" else "paragraph" if q["format"] == "text" else "choice"
            questions.append({"item_id": q["item_id"], "page": q["page"], "kind": kind, "title": q["text"],
                              "options": q["options"]})
        title = f"{report.get('title') or 'The future of ' + system} — {GROUP_NAMES.get(role, role)}"
        forms.append({"group": role, "title": title, "questions": questions,
                      "description": COVER.format(organisation=report.get("organisation") or "Our organisation", system=system)})
    return {"forms": forms, "pages": {str(k): v for k, v in PAGES.items()}, "notes": {str(k): v for k, v in PAGE_NOTES.items()}}


def apps_script(engagement_path) -> str:
    spec = form_specs(engagement_path)
    return SCRIPT.replace("__SPEC__", json.dumps(spec, ensure_ascii=False, indent=1)).replace("__SHUFFLE__", ", ".join(SHUFFLE))
