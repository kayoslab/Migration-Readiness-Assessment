"""`mra review`: a language model reads the report as the executive it is written for and lists what it leaves
unanswered, unclear or unconvincing. For the analyst only: the output goes to Output/<name>-review.md, never into
the report. Not run on client engagements (engagement.yaml → report.client_engagement: true).
"""

from __future__ import annotations

import shutil
from pathlib import Path

import pydantic

REVIEW_INSTRUCTIONS = """You are a member of the executive leadership team receiving this report before a board
meeting at which you must approve or reject what it asks for. You receive the report's content as JSON: the decision
requested, the findings, the qualifications, the money, the plan and the automated board-readiness checks.

Read it critically, as an experienced executive would read an advisory firm's report. Return:
- questions: up to ten questions the report leaves unanswered, or points where it is unclear, inconsistent or
  unconvincing — each with where in the report it arises and why it matters for the decision. Do not ask for
  anything the report already answers; check before you ask.
- strengths: up to five things the report does well, briefly.
Use British English. Do not invent facts; refer to the content you were given."""


class Question(pydantic.BaseModel):
    question: str
    where: str
    why: str


class ReviewOut(pydantic.BaseModel):
    questions: list[Question]
    strengths: list[str]


def review(engagement_path: str | Path, draws: int | None = None) -> Path:
    from .assess import assess
    from .config import LLMSettings
    from .llm import Cache, LLMClient, _cached, run_sync
    from .narrative import findings_payload
    from .report_v3 import build_context
    from .rubric import failures, run as run_rubric

    assessment = assess(engagement_path, draws=draws)
    eng = assessment.engagement
    if (eng.config.get("report") or {}).get("client_engagement"):
        raise PermissionError("mra review is a local tool for the analyst and is not run on client engagements.")
    root = Path(__file__).resolve().parents[1]
    name = Path(engagement_path).resolve().parent.name
    out = root / "Output" / "build-v3" / f"{name}-review"
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    ctx = build_context(assessment, out, root)
    payload = findings_payload(ctx) | {"board_readiness_failures": failures(run_rubric(ctx)),
                                       "budget": ctx.get("budget"), "risks": ctx["risks"]["risks"]}
    settings = LLMSettings(**(eng.config.get("llm") or {}))
    client = LLMClient.from_settings(settings)
    client.require_key()
    result = run_sync(_cached(client, Cache(eng.root / "Output" / "llm_cache"), "review", REVIEW_INSTRUCTIONS,
                              payload, ReviewOut))
    lines = [f"# Executive review of the {name} report", "",
             "Generated by `mra review` for the analyst. Not part of the report.", "", "## Questions", ""]
    for i, q in enumerate(result.get("questions", []), 1):
        lines += [f"{i}. **{q['question']}**", f"   - Where: {q['where']}", f"   - Why it matters: {q['why']}", ""]
    lines += ["## Strengths", ""] + [f"- {s}" for s in result.get("strengths", [])]
    path = root / "Output" / f"{name}-review.md"
    path.write_text("\n".join(lines) + "\n")
    return path
